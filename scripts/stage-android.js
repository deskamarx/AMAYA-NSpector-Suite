/** stage-android.js — build the Capacitor web bundle for the native Android app. */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const WEB = path.join(ROOT, 'web');
const AMAYA = path.join(ROOT, 'vendor', 'amaya');
const OUT = path.join(ROOT, 'android-web');

const API = process.env.SUITE_API_BASE || 'https://amaya-nspector-docker.onrender.com';
const WS = process.env.SUITE_WS_URL || API.replace(/^http/, 'ws') + '/ws';

function rm(p) { fs.rmSync(p, { recursive: true, force: true }); }
function copy(src, dest) { fs.cpSync(src, dest, { recursive: true }); }

function replace(file, from, to, label) {
  const source = fs.readFileSync(file, 'utf8');
  if (!source.includes(from)) throw new Error('Missing marker in ' + label + ': ' + from);
  fs.writeFileSync(file, source.replace(from, to), 'utf8');
}

function main() {
  rm(OUT);
  fs.mkdirSync(OUT, { recursive: true });

  // Full shell + native locale-aware AMAYA snapshot, served from the app bundle.
  copy(WEB, OUT);
  const pwa = path.join(OUT, 'amaya-imei-control-center');
  copy(AMAYA, pwa);

  fs.writeFileSync(path.join(OUT, 'android-config.js'), [
    '/* Generated by scripts/stage-android.js — do not edit by hand. */',
    'window.SUITE_NATIVE = true;',
    'window.SUITE_API_BASE = ' + JSON.stringify(API) + ';',
    'window.SUITE_WS_URL = ' + JSON.stringify(WS) + ';'
  ].join('\n') + '\n', 'utf8');

  const index = path.join(OUT, 'index.html');
  replace(index,
    '<script src="i18n.js"></script>',
    '<script src="android-config.js"></script>\n<script src="android-native.js"></script>\n<script src="i18n.js"></script>',
    'shell index');
  replace(index,
    "connect-src 'self' ws: wss:",
    "connect-src 'self' " + API + ' ' + WS + ' ws: wss:',
    'shell CSP');

  const pwaIndex = path.join(pwa, 'index.html');
  fs.copyFileSync(path.join(WEB, 'android-native.js'), path.join(pwa, 'assets', 'suite-native-ui.js'));
  replace(pwaIndex,
    '</body>',
    '<script src="./assets/suite-native-ui.js"></script>\n  </body>',
    'AMAYA index');

  console.log('Android web bundle staged: ' + OUT);
  console.log('  API base: ' + API);
  console.log('  WS base:  ' + WS);
}

main();
